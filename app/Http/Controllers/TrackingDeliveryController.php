     * @param  \Illuminate\Http\Request  $request
     * @param  int  $id
     * @return \Illuminate\Http\Response
     */
    public function update(Request $request, $id)
    {
        try {
            $validator = $request->validate([
                'status' => "required",
            ]);

            if ($validator) {
                $tracking = TrackingDelivery::find($id);
                $tracking->status = $request->status;
                $tracking->save();

                return redirect()->route('tracking.index')->with('success', 'Status berhasil diubah');
            } else {
                return redirect()->route('tracking.index')->with('error', 'Status gagal diubah');
            }
        } catch (\Throwable $th) {
